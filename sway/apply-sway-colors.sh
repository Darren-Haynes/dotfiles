#!/bin/bash
# Set sway/SwayFX window border colours from the theme family + variant + accent.
#   apply-sway-colors.sh <family> <dark|light> <accent>
#
# Focused window border = the accent (dark or light shade for the variant);
# unfocused/inactive borders = a neutral matching the variant. Titlebars are
# always drawn with the family's dark greys.
# Writes ~/.local/state/bubblegum/sway-colors.conf (included by sway/config so
# reloads and logins keep it) and applies the same lines to the running sway.

DOTFILES="$HOME/Dotfiles"
# shellcheck source=../bash-scripts/theme-palette.sh
. "$DOTFILES/bash-scripts/theme-palette.sh"

family="$1"; variant="$2"; accent="$3"
accent_hex=$(accent_color "$family" "$variant" "$accent") || exit 1
dark_accent=$(accent_color "$family" dark "$accent")

inactive=$(theme_color "$family" "$variant" inactive)
raised=$(theme_color "$family" dark raised)
bg=$(theme_color "$family" dark bg)
base=$(theme_color "$family" dark base)
border=$(theme_color "$family" dark border)
muted=$(theme_color "$family" dark muted)
strong=$(theme_color "$family" dark strong)
unfocused_ind=$(theme_color "$family" dark inactive)
# Bubblegum keeps its original green focus indicator; other families use the accent.
indicator="$dark_accent"
[ "$family" = bubblegum ] && indicator="#488F6D"

OUT="$HOME/.local/state/bubblegum/sway-colors.conf"
mkdir -p "$(dirname "$OUT")"

# Only the last field (child_border, the window border) follows the accent.
cat > "$OUT" <<EOF
# Generated by sway/apply-sway-colors.sh ($family, $variant, $accent) - do not edit.
client.focused          "$raised" "$raised" "$strong" "$indicator" "$accent_hex"
client.focused_inactive "$border" "$bg" "$muted" "$base" "$inactive"
client.unfocused        "$base" "$bg" "$muted" "$unfocused_ind" "$inactive"
EOF

# Apply live without a reload (a reload would also reset gaps/titlebar toggles).
grep '^client\.' "$OUT" | while IFS= read -r line; do
    swaymsg "$line" >/dev/null 2>&1
done
