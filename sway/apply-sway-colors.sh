#!/bin/bash
# Set sway/SwayFX window border colours from the Bubblegum variant + accent.
#   apply-sway-colors.sh <dark|light> <pink|blue|green>
#
# Focused window border = the accent (dark or light shade for the variant);
# unfocused/inactive borders = a neutral matching the variant.
# Writes ~/.local/state/bubblegum/sway-colors.conf (included by sway/config so
# reloads and logins keep it) and applies the same lines to the running sway.

DOTFILES="$HOME/Dotfiles"
# shellcheck source=../bash-scripts/bubblegum-accents.sh
. "$DOTFILES/bash-scripts/bubblegum-accents.sh"

variant="$1"; accent="$2"
accent_hex=$(accent_color "$variant" "$accent") || exit 1

if [ "$variant" = dark ]; then
    inactive="#222222"
else
    inactive="#c8c8c8"
fi

OUT="$HOME/.local/state/bubblegum/sway-colors.conf"
mkdir -p "$(dirname "$OUT")"

# Same titlebar/indicator colours as the defaults in sway/config; only the
# last field (child_border, the window border) changes.
cat > "$OUT" <<EOF
# Generated by sway/apply-sway-colors.sh ($variant, $accent) - do not edit.
client.focused          "#3A3A3A" "#3A3A3A" "#ffffff" "#488F6D" "$accent_hex"
client.focused_inactive "#454545" "#2A2A2A" "#A7A7A7" "#303030" "$inactive"
client.unfocused        "#303030" "#2A2A2A" "#A7A7A7" "#222222" "$inactive"
EOF

# Apply live without a reload (a reload would also reset gaps/titlebar toggles).
grep '^client\.' "$OUT" | while IFS= read -r line; do
    swaymsg "$line" >/dev/null 2>&1
done
