#!/bin/bash
# Generate ~/.config/dunst/dunstrc.d/10-colors.conf for a family + variant + accent.
#   apply-dunst-colors.sh <family> <dark|light> <accent>
#
# Bubblegum keeps using the hand-tuned dunst/colors-{dark,light}.conf files
# (pink accent and icon theme swapped for the chosen ones). Other families are
# generated from the palette roles in bash-scripts/theme-palette.sh.

DOTFILES="$HOME/Dotfiles"
# shellcheck source=../bash-scripts/theme-palette.sh
. "$DOTFILES/bash-scripts/theme-palette.sh"

family="$1"; variant="$2"; accent="$3"
DUNST_SRC="$DOTFILES/dunst"
DUNST_CFG="$HOME/.config/dunst"
OUT="$DUNST_CFG/dunstrc.d/10-colors.conf"
icon_theme="$(icon_theme_name "$family" "$variant" "$accent")"

mkdir -p "$DUNST_CFG/dunstrc.d"
ln -sfn "$DUNST_SRC/dunstrc" "$DUNST_CFG/dunstrc"
rm -f "$OUT"

if [ "$family" = bubblegum ]; then
    sed "s/$(accent_color bubblegum "$variant" pink)/$(accent_color bubblegum "$variant" "$accent")/Ig; s/$(icon_theme_name bubblegum "$variant" pink)/${icon_theme}/g" \
        "$DUNST_SRC/colors-$variant.conf" > "$OUT"
else
    bg=$(theme_color "$family" "$variant" bg)
    fg=$(theme_color "$family" "$variant" fg)
    muted=$(theme_color "$family" "$variant" muted)
    border=$(theme_color "$family" "$variant" border)
    strong=$(theme_color "$family" "$variant" strong)
    error=$(theme_color "$family" "$variant" error)
    critical_bg=$(theme_color "$family" "$variant" critical_bg)
    accent_hex=$(accent_color "$family" "$variant" "$accent")
    [ "$variant" = light ] && strong="$fg"
    cat > "$OUT" <<EOF
# $(theme_family_label "$family") ($variant, $accent) - generated by sway/apply-dunst-colors.sh
[global]
    frame_color = "$accent_hex"
    separator_color = frame
    highlight = "$accent_hex"
    icon_theme = "$icon_theme"

[urgency_low]
    background = "$bg"
    foreground = "$muted"
    frame_color = "$border"
    highlight = "$accent_hex"

[urgency_normal]
    background = "$bg"
    foreground = "$fg"
    frame_color = "$accent_hex"
    highlight = "$accent_hex"

[urgency_critical]
    background = "$critical_bg"
    foreground = "$strong"
    frame_color = "$error"
    highlight = "$error"
EOF
fi
dunstctl reload 2>/dev/null
