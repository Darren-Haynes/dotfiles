#!/bin/bash
# Write ~/.local/state/bubblegum/rofi-colors.rasi (imported by rofi/bubblegum.rasi)
# for the active theme family + accent. Rofi is always dark, so it uses the dark
# variant of the family.
#   apply-rofi-colors.sh <family> <accent>

DOTFILES="$HOME/Dotfiles"
# shellcheck source=../bash-scripts/theme-palette.sh
. "$DOTFILES/bash-scripts/theme-palette.sh"

family="$1"; accent="$2"
OUT="$THEME_STATE_DIR/rofi-colors.rasi"
mkdir -p "$THEME_STATE_DIR"

# Bubblegum's rofi has always used a fixed ice-blue border regardless of the
# accent; keep that. Other families follow their accent.
rofi_accent=$(accent_color "$family" dark "$accent")
[ "$family" = bubblegum ] && rofi_accent="#87d7ff"

# rofi wants #rrggbbaa
c() { printf '%sff' "$(theme_color "$family" dark "$1")"; }

cat > "$OUT" <<EOF
/* Generated by sway/apply-rofi-colors.sh ($family, $accent) - do not edit. */
* {
    bg-frame:       $(c bg);
    bg-toolbar:     $(c raised);
    txt-highlight:  $(c fg);
    txt-muted:      $(c muted);
    accent-blue:    ${rofi_accent}ff;
}
EOF
